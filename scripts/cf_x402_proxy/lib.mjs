// Offer summary for the ledger (what the 402 offered; read from PAYMENT-REQUIRED, never stored raw)

export function summarizeAccepts(headerValue) {
  try {
    const decoded = JSON.parse(Buffer.from(headerValue, 'base64').toString('utf8'));
    if (!Array.isArray(decoded?.accepts)) return undefined;
    return decoded.accepts.slice(0, 32).map((a) => ({
      scheme: typeof a?.scheme === 'string' ? a.scheme.slice(0, 32) : undefined,
      network: typeof a?.network === 'string' ? a.network.slice(0, 64) : undefined,
      asset: typeof a?.asset === 'string' ? a.asset.slice(0, 66) : undefined,
      amount: typeof a?.amount === 'string' ? a.amount.slice(0, 40) : undefined,
      pay_to: typeof a?.payTo === 'string' ? a.payTo.slice(0, 66) : undefined,
    }));
  } catch {
    return undefined;
  }
}

