// Cloudflare AI Gateway Machine Payments (x402) behind a local OpenAI-compatible endpoint.
//
// Hermes speaks OpenAI chat completions to a base_url + key. Cloudflare's x402-eligible endpoint is
// `POST /accounts/{id}/ai/run` (not its OpenAI-compatible path), answered with 402 + an x402 v2
// `upto` offer on Base USDC. This module translates the request, pays the 402 with radius-sdk's
// createRadiusFetch, records every attempt in the template's buyer ledger, and translates back.
//
// Never logged or persisted: private keys, the Cloudflare token, PAYMENT-SIGNATURE, the raw
// PAYMENT-REQUIRED header, prompts or completions.
import { createHash, randomUUID, timingSafeEqual } from 'node:crypto';
import { mkdirSync, openSync, closeSync, fsyncSync, readFileSync, existsSync, writeSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRadiusFetch, RadiusPaymentError } from 'radius-sdk/client';
import { privateKeyToAccount } from 'viem/accounts';

export const BASE_NETWORK = 'eip155:8453';
export const BASE_USDC = '0x833589fcd6edb6e08f4c7c32d4f71b54bda02913';
export const PERMIT2_ADDRESS = '0x000000000022D473030F116dDEE9F6B43aC78BA3';
// @x402/evm's x402UptoPermit2Proxy (CREATE2, same address on every chain).
export const UPTO_PERMIT2_PROXY = '0x4020A4f3b7b90ccA423B9fabCc0CE57C6C240002';
const USDC_DECIMALS = 6;
const DEFAULT_API_BASE = 'https://api.cloudflare.com/client/v4';
const DAY_MS = 24 * 60 * 60 * 1000;
export const MAX_REQUEST_BYTES = 8 * 1024 * 1024;
const MAX_UPSTREAM_BYTES = 8 * 1024 * 1024;
const MAX_QUEUE = 16;
export const LEDGER_SOURCE = 'cf-x402-proxy';

// OpenAI chat-completions fields forwarded inside `/ai/run`'s `input`. Everything else (stream,
// stream_options, provider routing hints, user ids, metadata) is dropped.
const FORWARDED_FIELDS = [
  'messages', 'tools', 'tool_choice', 'parallel_tool_calls', 'temperature', 'top_p', 'stop', 'seed',
  'frequency_penalty', 'presence_penalty', 'response_format', 'reasoning_effort',
];

