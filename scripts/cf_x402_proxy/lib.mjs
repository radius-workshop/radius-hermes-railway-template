// OpenAI chat completions <-> Cloudflare /ai/run

export function toRunBody(chat, config) {
  if (!chat || typeof chat !== 'object' || Array.isArray(chat)) throw new RequestError(400, 'request body must be a JSON object');
  if (!Array.isArray(chat.messages) || chat.messages.length === 0) throw new RequestError(400, 'messages must be a non-empty array');
  const input = {};
  for (const k of FORWARDED_FIELDS) if (chat[k] !== undefined) input[k] = chat[k];
  const asked = Number(chat.max_tokens ?? chat.max_completion_tokens);
  // Cloudflare sizes the authorised maximum from the request (max_tokens), so always send one.
  input.max_tokens = Number.isInteger(asked) && asked > 0 ? Math.min(asked, config.maxTokens) : config.maxTokens;
  // The model is the operator's choice, not the caller's: an eligible model, priced as configured.
  return { model: config.model, input };
}

function toolCallsFrom(raw) {
  if (!Array.isArray(raw) || raw.length === 0) return undefined;
  return raw.map((c, i) => {
    if (c && c.function) {
      const args = c.function.arguments;
      return { id: c.id || `call_${i}`, type: 'function', function: { name: c.function.name, arguments: typeof args === 'string' ? args : JSON.stringify(args ?? {}) } };
    }
    // Workers AI native shape: { name, arguments: object }
    return { id: c?.id || `call_${i}`, type: 'function', function: { name: c?.name, arguments: typeof c?.arguments === 'string' ? c.arguments : JSON.stringify(c?.arguments ?? {}) } };
  });
}

/**
 * Normalise a `/ai/run` answer to an OpenAI chat.completion. Accepts the Cloudflare v4 envelope
 * (`{ result, success }`) around either an OpenAI-shaped completion (`choices`) or the Workers AI
 * native shape (`{ response, tool_calls, usage }`). Returns undefined for anything else.
 */
export function toChatCompletion(body, model) {
  const r = body && typeof body === 'object' && body.result && typeof body.result === 'object' ? body.result : body;
  if (!r || typeof r !== 'object') return undefined;
  const created = Math.floor(Date.now() / 1000);
  if (Array.isArray(r.choices) && r.choices.length > 0) {
    return {
      id: r.id || `chatcmpl-${randomUUID()}`,
      object: 'chat.completion',
      created: r.created || created,
      model: r.model || model,
      choices: r.choices.map((c, i) => {
        const message = { role: 'assistant', content: c?.message?.content ?? null };
        const calls = toolCallsFrom(c?.message?.tool_calls);
        if (calls) message.tool_calls = calls;
        if (c?.message?.reasoning_content) message.reasoning_content = c.message.reasoning_content;
        return { index: c?.index ?? i, message, finish_reason: c?.finish_reason ?? (calls ? 'tool_calls' : 'stop') };
      }),
      ...(r.usage ? { usage: r.usage } : {}),
    };
  }
  if (typeof r.response === 'string' || Array.isArray(r.tool_calls)) {
    const calls = toolCallsFrom(r.tool_calls);
    const message = { role: 'assistant', content: typeof r.response === 'string' ? r.response : null };
    if (calls) message.tool_calls = calls;
    return {
      id: `chatcmpl-${randomUUID()}`,
      object: 'chat.completion',
      created,
      model,
      choices: [{ index: 0, message, finish_reason: calls ? 'tool_calls' : 'stop' }],
      ...(r.usage ? { usage: r.usage } : {}),
    };
  }
  return undefined;
}

/** A finished completion as an OpenAI SSE stream (Cloudflare is called without streaming). */
export function toSse(completion) {
  const base = { id: completion.id, object: 'chat.completion.chunk', created: completion.created, model: completion.model };
  const events = [];
  for (const choice of completion.choices) {
    const delta = { role: 'assistant' };
    if (choice.message.reasoning_content) delta.reasoning_content = choice.message.reasoning_content;
    if (choice.message.content != null) delta.content = choice.message.content;
    if (choice.message.tool_calls) delta.tool_calls = choice.message.tool_calls.map((c, index) => ({ index, ...c }));
    events.push({ ...base, choices: [{ index: choice.index, delta, finish_reason: null }] });
    events.push({ ...base, choices: [{ index: choice.index, delta: {}, finish_reason: choice.finish_reason }] });
  }
  if (completion.usage) events.push({ ...base, choices: [], usage: completion.usage });
  return events.map((e) => `data: ${JSON.stringify(e)}\n\n`).join('') + 'data: [DONE]\n\n';
}

