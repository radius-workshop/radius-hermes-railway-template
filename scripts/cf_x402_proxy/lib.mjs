// The payer

/**
 * Build the paying client. The signer only signs typed data: this process can never send or sign
 * a transaction, so no on-chain approval (and no sponsored `erc20ApprovalGasSponsoring` approve
 * transaction) can come from it. The Permit2 allowance is set up once, out of band
 * (approve-permit2.mjs), and is itself a lifetime spend ceiling.
 */
/**
 * A signer that signs only the two payment authorisations this proxy may give, each within the
 * per-request cap: the x402 `upto` Permit2 witness transfer (spender = x402UptoPermit2Proxy) and an
 * EIP-3009 USDC `TransferWithAuthorization` (x402 `exact`). Anything else, notably the EIP-2612
 * `Permit` that @x402/evm signs when a 402 advertises `eip2612GasSponsoring` (it would overwrite the
 * Permit2 allowance), is refused.
 */
export function guardedSigner(account, cap) {
  const same = (a, b) => typeof a === 'string' && a.toLowerCase() === b.toLowerCase();
  return {
    address: account.address,
    signTypedData: async (args) => {
      const { primaryType, domain = {}, message = {} } = args ?? {};
      if (primaryType === 'PermitWitnessTransferFrom') {
        if (domain.name !== 'Permit2' || !same(domain.verifyingContract, PERMIT2_ADDRESS) || Number(domain.chainId) !== 8453) throw new Error('refusing to sign: not Permit2 on Base');
        if (!same(message.spender, UPTO_PERMIT2_PROXY)) throw new Error('refusing to sign: Permit2 spender is not the x402 upto proxy');
        if (!same(message.permitted?.token, BASE_USDC) || BigInt(message.permitted?.amount ?? -1) > cap || BigInt(message.permitted?.amount ?? -1) < 0n) throw new Error('refusing to sign: Permit2 amount or token out of policy');
        return account.signTypedData(args);
      }
      if (primaryType === 'TransferWithAuthorization') {
        if (!same(domain.verifyingContract, BASE_USDC) || Number(domain.chainId) !== 8453) throw new Error('refusing to sign: not USDC on Base');
        if (BigInt(message.value ?? -1) > cap || BigInt(message.value ?? -1) < 0n) throw new Error('refusing to sign: transfer above the per-request cap');
        return account.signTypedData(args);
      }
      throw new Error(`refusing to sign typed data ${String(primaryType)}`);
    },
  };
}

export function createPayer(config, { fetch: baseFetch = globalThis.fetch } = {}) {
  const account = privateKeyToAccount(config.privateKey);
  const signer = guardedSigner(account, config.maxPerRequest);
  // Wallet reads (Permit2 allowance) through a hook-less client.
  const wallet = createRadiusFetch({
    network: 'base',
    ...(config.rpcUrl ? { rpcUrl: config.rpcUrl } : {}),
    protocols: ['x402'],
    signer,
    maxPerRequest: { amount: config.maxPerRequest.toString() },
    permit2Approval: 'never',
    onApprovalRequired: () => false,
  });

  /** A paying fetch whose hooks report into `ctx` (createRadiusFetch hooks are client-wide, so one per request). */
  const payerFor = (ctx) => createRadiusFetch({
    network: 'base',
    ...(config.rpcUrl ? { rpcUrl: config.rpcUrl } : {}),
    protocols: ['x402'],
    signer,
    maxPerRequest: { amount: config.maxPerRequest.toString() },
    permit2Approval: 'never',
    onApprovalRequired: () => false,
    fetch: async (input, init) => {
      const req = new Request(input, init);
      if (req.headers.has('payment-signature') || req.headers.has('x-payment')) ctx.sent = true;
      const res = await baseFetch(req);
      if (res.status === 402) {
        const header = res.headers.get('payment-required');
        if (header && !ctx.accepts) ctx.accepts = summarizeAccepts(header);
      }
      return res;
    },
    onPaymentRequired: async (offer) => {
      ctx.offer = offer;
      const decline = (reason) => {
        ctx.refusal = reason;
        return false;
      };
      if (offer.protocol !== 'x402' || offer.network.network !== BASE_NETWORK || offer.asset.toLowerCase() !== BASE_USDC) {
        return decline('offer is not Base USDC');
      }
      if (offer.scheme !== 'upto' && offer.scheme !== 'exact') return decline(`unsupported scheme ${offer.scheme}`);
      if (config.expectedPayTo && offer.payTo.toLowerCase() !== config.expectedPayTo) return decline('payTo does not match CF_X402_EXPECTED_PAY_TO');
      // Without an allowance covering the offer, @x402/evm would fall back to a sponsored-approval
      // extension if the 402 advertised one. Refuse instead: approvals happen only out of band.
      let allowance;
      try {
        allowance = await wallet.permit2Allowance();
      } catch {
        return decline('could not read the Permit2 allowance on Base (RPC error)');
      }
      if (allowance < BigInt(offer.amount)) {
        ctx.code = 'approval_required';
        return decline(`Permit2 allowance ${atomicToUsdc(allowance)} USDC is below the offer's ${atomicToUsdc(offer.amount)} USDC; run approve-permit2.mjs`);
      }
      const reservation = ctx.budget.reserve(BigInt(offer.amount));
      if (!reservation) {
        ctx.code = 'budget_exceeded';
        return decline(`rolling 24h budget of ${atomicToUsdc(ctx.budget.limit)} USDC would be exceeded`);
      }
      ctx.reservation = reservation;
      // Durable before signing: a crash from here on leaves a row counted at the authorised maximum.
      if (ctx.onSigning && !ctx.onSigning()) return decline('payment ledger unavailable; not signing');
      ctx.signing = true;
      return true;
    },
    onPaid: (receipt) => {
      ctx.receipt = receipt;
    },
  });

  const call = (ctx, init) => payerFor(ctx)(config.runUrl, init);
  return { call, address: account.address, wallet };
}

