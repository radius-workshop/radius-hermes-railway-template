/** Read and validate the proxy configuration from environment variables. Throws ConfigError. */
export function loadConfig(env = process.env) {
  const accountId = (env.CLOUDFLARE_ACCOUNT_ID ?? '').trim();
  if (!/^[0-9a-f]{32}$/i.test(accountId)) throw new ConfigError('CLOUDFLARE_ACCOUNT_ID must be the 32-character Cloudflare account ID');
  const apiToken = (env.CLOUDFLARE_API_TOKEN ?? '').trim();
  if (!apiToken) throw new ConfigError('CLOUDFLARE_API_TOKEN is required (Workers AI permission)');
  const privateKey = (env.CF_X402_PRIVATE_KEY || env.RADIUS_PRIVATE_KEY || '').trim();
  if (!/^0x[0-9a-fA-F]{64}$/.test(privateKey)) throw new ConfigError('A wallet key is required: RADIUS_PRIVATE_KEY (agent wallet) or CF_X402_PRIVATE_KEY, 0x-prefixed 32-byte hex');
  const proxyKey = (env.CF_X402_PROXY_KEY ?? '').trim();
  if (proxyKey.length < 32) throw new ConfigError('CF_X402_PROXY_KEY (local bearer token, generated by entrypoint.sh) must be at least 32 characters');

  const apiBase = (env.CF_X402_API_BASE || DEFAULT_API_BASE).replace(/\/+$/, '');
  const apiUrl = new URL(apiBase);
  if (apiUrl.protocol !== 'https:' && !(apiUrl.protocol === 'http:' && isLoopbackHost(apiUrl.hostname))) {
    throw new ConfigError('CF_X402_API_BASE must be https (plain http is allowed only for a loopback test server)');
  }
  const rpcUrl = (env.CF_X402_BASE_RPC_URL ?? '').trim() || undefined;
  if (rpcUrl) {
    const u = new URL(rpcUrl);
    if (u.protocol !== 'https:' && !(u.protocol === 'http:' && isLoopbackHost(u.hostname))) throw new ConfigError('CF_X402_BASE_RPC_URL must be https');
  }
  const expectedPayTo = (env.CF_X402_EXPECTED_PAY_TO ?? '').trim().toLowerCase() || undefined;
  if (expectedPayTo && !/^0x[0-9a-f]{40}$/.test(expectedPayTo)) throw new ConfigError('CF_X402_EXPECTED_PAY_TO must be a 0x address');

  const maxPerRequest = usdcToAtomic(env.CF_X402_MAX_PER_REQUEST || '0.15', 'CF_X402_MAX_PER_REQUEST');
  const dailyBudget = usdcToAtomic(env.CF_X402_DAILY_BUDGET || '2', 'CF_X402_DAILY_BUDGET');
  if (maxPerRequest > dailyBudget) throw new ConfigError('CF_X402_MAX_PER_REQUEST cannot exceed CF_X402_DAILY_BUDGET');

  const home = env.HERMES_HOME || '/data/.hermes';
  return {
    accountId,
    apiToken,
    privateKey,
    proxyKey,
    runUrl: `${apiBase}/accounts/${accountId}/ai/run`,
    // What the ledger shows instead of the URL: no account ID.
    ledgerUrl: `${apiUrl.origin}/client/v4/accounts/{account}/ai/run`,
    model: (env.CF_X402_MODEL || 'z-ai/glm-4.7-flash').trim(),
    maxTokens: positiveInt(env.CF_X402_MAX_TOKENS, 8192, 'CF_X402_MAX_TOKENS', 131072),
    contextLength: positiveInt(env.CF_X402_CONTEXT_LENGTH, undefined, 'CF_X402_CONTEXT_LENGTH', 2_000_000),
    maxPerRequest,
    dailyBudget,
    timeoutMs: positiveInt(env.CF_X402_TIMEOUT_SECONDS, 120, 'CF_X402_TIMEOUT_SECONDS', 900) * 1000,
    concurrency: positiveInt(env.CF_X402_MAX_CONCURRENCY, 2, 'CF_X402_MAX_CONCURRENCY', 16),
    port: positiveInt(env.CF_X402_PORT, 8650, 'CF_X402_PORT', 65535),
    rpcUrl,
    expectedPayTo,
    ledgerPath: env.X402_LEDGER_PATH || join(home, 'x402', 'ledger.jsonl'),
  };
}

// ---------------------------------------------------------------------------------------------
// Ledger: the same JSONL file and row shape as plugins/x402 (one row per event, latest row per id wins)

export function appendLedger(path, row) {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  // O_APPEND with a single write per line: concurrent appenders (the Python plugin uses flock) do
  // not interleave lines this short on Linux local filesystems.
  const fd = openSync(path, 'a', 0o600);
  try {
    writeSync(fd, JSON.stringify(row) + '\n');
    fsyncSync(fd);
  } finally {
    closeSync(fd);
  }
}

/** Spend charged against the rolling budget by earlier proxy rows (settled, or the authorised max when unknown). */
export function spentFromLedger(path, now = Date.now()) {
  if (!existsSync(path)) return [];
  const latest = new Map();
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    try {
      const row = JSON.parse(line);
      if (row && typeof row.id === 'string' && row.requested_by === LEDGER_SOURCE) latest.set(row.id, row);
    } catch {
      /* malformed lines are counted by the plugin's x402_ledger tool */
    }
  }
  const out = [];
  for (const row of latest.values()) {
    const ts = Date.parse(row.ts);
    if (!Number.isFinite(ts) || now - ts > DAY_MS) continue;
    // Settled calls count what was charged; calls that may still settle (including a crash after
    // the `signing` row) count their authorised maximum. Refusals, rejections and errors cost nothing.
    const atomic = row.outcome === 'settlement_reported' ? row.settled_atomic : row.outcome === 'payment_unknown' ? row.authorized_max_atomic : undefined;
    if (typeof atomic === 'string' && /^\d+$/.test(atomic) && atomic !== '0') out.push({ ts, atomic: BigInt(atomic) });
  }
  return out;
}

// ---------------------------------------------------------------------------------------------
// Rolling 24h budget with reservations for in-flight payments

export class Budget {
  constructor(limit, entries = [], now = () => Date.now()) {
    this.limit = limit;
    this.entries = entries.map((e) => ({ ...e }));
    this.now = now;
  }

  used() {
    const cutoff = this.now() - DAY_MS;
    this.entries = this.entries.filter((e) => e.ts >= cutoff);
    return this.entries.reduce((sum, e) => sum + e.atomic, 0n);
  }

  /** Reserve `atomic` now, or return undefined when it would exceed the limit. */
  reserve(atomic) {
    if (this.used() + atomic > this.limit) return undefined;
    const entry = { ts: this.now(), atomic };
    this.entries.push(entry);
    return entry;
  }

  /** Replace a reservation by what was actually charged (0n releases it). */
  settle(entry, atomic) {
    entry.atomic = atomic;
  }
}

