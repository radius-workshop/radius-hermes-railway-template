// HTTP handler

function sendJson(res, status, body) {
  const text = JSON.stringify(body);
  res.writeHead(status, { 'content-type': 'application/json', 'cache-control': 'no-store' });
  res.end(text);
}

function openAiError(res, status, message, code) {
  sendJson(res, status, { error: { message, type: code, code } });
}

async function readBody(req, limit) {
  const chunks = [];
  let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > limit) throw new RequestError(413, `request body exceeds ${limit} bytes`);
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}

async function readCapped(response, limit) {
  const reader = response.body?.getReader();
  if (!reader) return '';
  const chunks = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.length;
    if (size > limit) {
      await reader.cancel();
      throw new Error(`upstream response exceeds ${limit} bytes`);
    }
    chunks.push(value);
  }
  return Buffer.concat(chunks).toString('utf8');
}

function authorized(req, key) {
  const header = req.headers.authorization ?? '';
  const m = /^Bearer\s+(.+)$/i.exec(header);
  if (!m) return false;
  const a = Buffer.from(m[1].trim());
  const b = Buffer.from(key);
  return a.length === b.length && timingSafeEqual(a, b);
}

/** Cloudflare's `{ errors: [{ code, message }] }`, cut down to something safe to show the agent. */
function upstreamErrorMessage(text) {
  try {
    const j = JSON.parse(text);
    const e = Array.isArray(j?.errors) && j.errors[0];
    if (e) return `${e.code ?? ''} ${String(e.message ?? '').slice(0, 300)}`.trim();
    if (j?.error) return String(j.error.message ?? j.error).slice(0, 300);
  } catch {
    /* not JSON */
  }
  return text.slice(0, 300);
}

export function createHandler(config, { payer, budget, log = (line) => console.log(line), now = () => Date.now() }) {
  let active = 0;
  const waiting = [];
  const acquire = () => {
    if (active < config.concurrency) {
      active++;
      return Promise.resolve();
    }
    if (waiting.length >= MAX_QUEUE) return undefined;
    return new Promise((resolve) => waiting.push(resolve));
  };
  const release = () => {
    const next = waiting.shift();
    if (next) next();
    else active--;
  };

  // Hermes retries a failed call (agent.api_max_retries, default 3). A retry of an identical body
  // joins the call still in flight, or gets its result for DEDUPE_MS afterwards, instead of paying again.
  const inflight = new Map();
  const recent = new Map();
  // Tripped when Cloudflare answers without an x402 challenge (billed to the account, not the wallet).
  let breaker;

  const ledger = (ctx, event, outcome, extra = {}) => {
    appendLedger(config.ledgerPath, {
      id: ctx.id,
      ts: new Date(ctx.started).toISOString(),
      url: config.ledgerUrl,
      method: 'POST',
      memo: `cloudflare-x402 inference ${config.model}`,
      requested_by: LEDGER_SOURCE,
      event,
      outcome,
      network: BASE_NETWORK,
      asset_symbol: 'USDC',
      ...extra,
    });
  };

  return async function handler(req, res) {
    const url = new URL(req.url, 'http://127.0.0.1');
    if (req.method === 'GET' && url.pathname === '/health') return sendJson(res, breaker ? 503 : 200, { ok: !breaker, ...(breaker ? { tripped: breaker } : {}) });
    if (!authorized(req, config.proxyKey)) return openAiError(res, 401, 'invalid local proxy key', 'unauthorized');
    if (req.method === 'GET' && (url.pathname === '/v1/models' || url.pathname === '/models')) {
      const model = { id: config.model, object: 'model', owned_by: 'cloudflare-x402' };
      if (config.contextLength) model.context_length = config.contextLength;
      return sendJson(res, 200, { object: 'list', data: [model] });
    }
    if (req.method !== 'POST' || (url.pathname !== '/v1/chat/completions' && url.pathname !== '/chat/completions')) {
      return openAiError(res, 404, 'only POST /v1/chat/completions is served', 'not_found');
    }
    if (breaker) return openAiError(res, 503, `cf-x402 proxy stopped: ${breaker}. Fix the Cloudflare setup and restart the service.`, 'circuit_open');

    let chat;
    let runBody;
    try {
      const raw = await readBody(req, MAX_REQUEST_BYTES);
      try {
        chat = JSON.parse(raw.toString('utf8'));
      } catch {
        throw new RequestError(400, 'request body is not JSON');
      }
      runBody = toRunBody(chat, config);
    } catch (e) {
      if (e instanceof RequestError) return openAiError(res, e.status, e.message, e.code);
      throw e;
    }
    const wantsStream = chat.stream === true;
    const bodyText = JSON.stringify(runBody);
    const key = createHash('sha256').update(bodyText).digest('hex');

    const t = now();
    for (const [k, v] of recent) if (t - v.at > DEDUPE_MS) recent.delete(k);
    let pending = inflight.get(key);
    const cached = recent.get(key);
    if (cached) {
      log(`[cf-x402] identical request within ${DEDUPE_MS / 1000}s; returning the earlier result (no new payment)`);
      return finish(res, cached.result, wantsStream);
    }
    if (pending) {
      log('[cf-x402] identical request already in flight; joining it (no new payment)');
      return finish(res, await pending, wantsStream);
    }
    pending = execute(bodyText);
    inflight.set(key, pending);
    let result;
    try {
      result = await pending;
    } finally {
      inflight.delete(key);
    }
    // Remember paid or payment-unknown results; refusals and pre-payment errors are free to retry.
    if (result.outcome === 'settlement_reported' || result.outcome === 'payment_unknown') recent.set(key, { at: now(), result });
    return finish(res, result, wantsStream);
  };

  async function execute(bodyText) {
    const slot = acquire();
    if (!slot) return { outcome: 'error', error: { status: 429, message: 'too many queued inference requests', code: 'rate_limited' } };
    await slot;
    const ctx = { id: randomUUID(), started: now(), budget, signing: false, sent: false };
    ctx.onSigning = () => {
      try {
        ledger(ctx, 'signing', 'payment_unknown', paymentFields(ctx));
        return true;
      } catch {
        return false;
      }
    };
    const t0 = now();
    try {
      try {
        // Intent first; no request is made if it cannot be recorded.
        ledger(ctx, 'started', 'pending');
      } catch {
        return { outcome: 'error', error: { status: 503, message: 'payment ledger unavailable; no request or payment attempted', code: 'ledger_unavailable' } };
      }
      const result = await runPaid(ctx, bodyText);
      // Nothing left the process: whatever the outcome, the reservation is released.
      if (ctx.reservation && !ctx.sent) budget.settle(ctx.reservation, 0n);
      try {
        ledger(ctx, 'completed', result.outcome, result.extra);
      } catch {
        log(`[cf-x402] WARNING: final ledger write failed for ${ctx.id}; pending intent remains`);
      }
      const x = result.extra ?? {};
      log(`[cf-x402] ${ctx.id} model=${config.model} http=${x.http_status ?? '-'} outcome=${result.outcome}` +
        (x.authorized_max ? ` max=${x.authorized_max}` : '') +
        (x.settled_atomic !== undefined ? ` settled=${atomicToUsdc(x.settled_atomic)} USDC` : '') +
        (x.tx_hash ? ` tx=${x.tx_hash}` : '') + (x.reason ? ` reason="${x.reason}"` : '') + ` ms=${now() - t0}`);
      if (!result.error && result.text !== undefined) {
        result.completion = toChatCompletion(safeJson(result.text), config.model);
        if (!result.completion) {
          // Paid but unreadable: return the text rather than an error the agent would retry (and pay for again).
          log(`[cf-x402] WARNING: ${ctx.id} unrecognised /ai/run response shape; returned as plain text`);
          result.completion = { id: `chatcmpl-${ctx.id}`, object: 'chat.completion', created: Math.floor(now() / 1000), model: config.model,
            choices: [{ index: 0, message: { role: 'assistant', content: result.text.slice(0, 20000) }, finish_reason: 'stop' }] };
        }
      }
      return result;
    } finally {
      release();
    }
  }

  async function runPaid(ctx, bodyText) {
    const signal = AbortSignal.timeout(config.timeoutMs);
    let response;
    try {
      response = await payer.call(ctx, {
        method: 'POST',
        headers: {
          authorization: `Bearer ${config.apiToken}`,
          // Without this header Cloudflare bills the account (Unified Billing credits) instead.
          'payment-method': 'x402',
          'content-type': 'application/json',
          accept: 'application/json',
        },
        body: bodyText,
        signal,
      });
    } catch (e) {
      return failed(ctx, e);
    }
    const extra = paymentFields(ctx);
    let text;
    try {
      text = await readCapped(response, MAX_UPSTREAM_BYTES);
    } catch {
      if (ctx.sent) return outcomeUnknown(ctx, extra, response.status, 'response body could not be read');
      return { outcome: 'error', extra: { ...extra, http_status: response.status, reason: 'response body could not be read' }, error: { status: 502, message: 'Cloudflare response could not be read', code: 'upstream_error' } };
    }
    const ok = response.status >= 200 && response.status < 300;
    if (!ctx.offer) {
      // Cloudflare did not ask for x402. A 2xx here was billed to the Cloudflare account, not the
      // wallet: deliver it (it is paid for) and refuse everything after it until a restart.
      const fields = { ...extra, http_status: response.status, delivery: ok ? 'delivered' : 'failed' };
      if (!ok) return { outcome: 'error', extra: fields, error: { status: mapStatus(response.status), message: `Cloudflare: ${upstreamErrorMessage(text)}`, code: 'upstream_error' } };
      breaker = 'Cloudflare answered without an x402 challenge, so the call was billed to the Cloudflare account';
      log(`[cf-x402] ERROR: ${ctx.id} ${breaker}. Refusing further requests until restart.`);
      return { text, outcome: 'no_payment_required', extra: { ...fields, billing: 'cloudflare_account' } };
    }
    const receipt = ctx.receipt;
    if (receipt && receipt.success) {
      const settled = BigInt(receipt.amount ?? ctx.offer.amount);
      budget.settle(ctx.reservation, settled);
      const fields = { ...extra, settled_atomic: settled.toString(), amount: atomicToUsdc(settled), amount_atomic: settled.toString(), tx_hash: receipt.transaction ?? '',
        explorer_url: receipt.explorerUrl ?? '', http_status: response.status, delivery: ok ? 'delivered' : 'failed', reconciliation: 'not_verified' };
      if (!ok) return { outcome: 'settlement_reported', extra: fields, error: { status: mapStatus(response.status), message: `Cloudflare (paid ${atomicToUsdc(settled)} USDC): ${upstreamErrorMessage(text)}`, code: 'upstream_error' } };
      return { text, outcome: 'settlement_reported', extra: fields };
    }
    // Signed and sent, but no successful settlement report: the authorisation stays redeemable until its deadline.
    return outcomeUnknown(ctx, extra, response.status, receipt ? `settlement failed: ${receipt.errorReason ?? 'unknown'}` : 'no PAYMENT-RESPONSE settlement header', ok ? text : undefined);
  }

  function outcomeUnknown(ctx, extra, status, reason, text) {
    const fields = { ...extra, http_status: status, reason, reconciliation: 'not_verified' };
    if (text !== undefined) return { text, outcome: 'payment_unknown', extra: { ...fields, delivery: 'delivered' } };
    return { outcome: 'payment_unknown', extra: { ...fields, delivery: 'failed' }, error: { status: 502, message: `x402 payment state unknown (${reason}); not retrying`, code: 'payment_unknown' } };
  }

  function failed(ctx, e) {
    const extra = paymentFields(ctx);
    const timeout = e?.name === 'TimeoutError' || e?.name === 'AbortError';
    if (e instanceof RadiusPaymentError && !ctx.sent) {
      if (e.code === 'declined') {
        const reason = ctx.refusal ?? 'declined';
        return { outcome: 'refused', extra: { ...extra, reason }, error: { status: 402, message: `x402 payment refused by local policy: ${reason}`, code: ctx.code ?? 'payment_refused' } };
      }
      return { outcome: 'refused', extra: { ...extra, reason: `${e.code}: ${e.message}`.slice(0, 300) }, error: { status: 402, message: `x402 payment not possible: ${e.message}`.slice(0, 400), code: e.code } };
    }
    if (e instanceof RadiusPaymentError && e.code === 'payment_rejected') {
      // Cloudflare answered the signed request with another 402: nothing was settled.
      if (ctx.reservation) budget.settle(ctx.reservation, 0n);
      const reason = String(e.details?.error ?? 'rejected').slice(0, 200);
      return { outcome: 'rejected', extra: { ...extra, reason: `payment rejected: ${reason}` }, error: { status: 402, message: `Cloudflare rejected the x402 payment (${reason})`, code: 'payment_rejected' } };
    }
    if (ctx.sent) return outcomeUnknown(ctx, extra, 0, timeout ? `timed out after ${config.timeoutMs / 1000}s` : 'request failed after the payment was sent');
    const reason = timeout ? `timed out after ${config.timeoutMs / 1000}s before payment` : ctx.signing ? 'payment could not be signed' : 'Cloudflare request failed before payment';
    return { outcome: 'error', extra: { ...extra, reason }, error: { status: 502, message: reason, code: 'upstream_unreachable' } };
  }

  function paymentFields(ctx) {
    const o = ctx.offer;
    const fields = {};
    if (ctx.accepts) fields.accepts = ctx.accepts;
    if (o) Object.assign(fields, { scheme: o.scheme, pay_to: o.payTo, authorized_max_atomic: o.amount, authorized_max: atomicToUsdc(o.amount) });
    return fields;
  }
}

const DEDUPE_MS = 120_000;

function mapStatus(status) {
  // 4xx stay 4xx (bad request, auth) so the agent does not retry them; everything else is a 502.
  return status >= 400 && status < 500 && status !== 402 ? status : 502;
}

function safeJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return undefined;
  }
}

function finish(res, result, stream) {
  if (result.error) return openAiError(res, result.error.status, result.error.message, result.error.code);
  if (stream) {
    res.writeHead(200, { 'content-type': 'text/event-stream', 'cache-control': 'no-store' });
    res.end(toSse(result.completion));
    return;
  }
  sendJson(res, 200, result.completion);
}
