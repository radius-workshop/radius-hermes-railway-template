// Amounts

/** "0.05" (USDC display units, at most 6 decimals) -> 50000n. */
export function usdcToAtomic(value, label) {
  const s = String(value ?? '').trim();
  if (!/^\d+(\.\d{1,6})?$/.test(s)) throw new ConfigError(`${label} must be a positive USDC amount with at most 6 decimals (got ${JSON.stringify(value)})`);
  const [whole, frac = ''] = s.split('.');
  const atomic = BigInt(whole) * 10n ** BigInt(USDC_DECIMALS) + BigInt(frac.padEnd(USDC_DECIMALS, '0'));
  if (atomic <= 0n) throw new ConfigError(`${label} must be greater than zero`);
  return atomic;
}

export function atomicToUsdc(atomic) {
  const a = BigInt(atomic);
  const whole = a / 10n ** BigInt(USDC_DECIMALS);
  const frac = (a % 10n ** BigInt(USDC_DECIMALS)).toString().padStart(USDC_DECIMALS, '0').replace(/0+$/, '');
  return frac ? `${whole}.${frac}` : `${whole}`;
}

function positiveInt(raw, fallback, label, max) {
  if (raw === undefined || raw === '') return fallback;
  const n = Number(raw);
  if (!Number.isInteger(n) || n <= 0 || n > max) throw new ConfigError(`${label} must be an integer between 1 and ${max} (got ${JSON.stringify(raw)})`);
  return n;
}

function isLoopbackHost(hostname) {
  return hostname === '127.0.0.1' || hostname === 'localhost' || hostname === '[::1]' || hostname === '::1';
}

